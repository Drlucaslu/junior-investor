"""Research Agent (PRD §6).

Pipeline — deterministic data first, language model second:
1. Resolve the query to tickers (regex / aliases / symbol search / LLM extraction).
2. Gather facts with tools in parallel (quote, profile, financials, valuation,
   SEC filings, news, web). Every fact gets a source id (S1, S2, ...).
3. Numeric tables (Financial Snapshot, Valuation) are rendered by the app from
   the data — never generated by the model.
4. The LLM writes the narrative sections from the facts pack only, citing [S#]
   and labelling Fact / Interpretation / Unknown.
5. Sources are appended deterministically.
"""
